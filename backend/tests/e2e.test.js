/**
 * @file e2e.test.js
 * @description Comprehensive Phase 5 End-to-End Integration Tests for CASETHREAD.
 * Tests full dataflow: Auth -> Case DB -> C Core DSA Engine (Real Binary Execution) -> Graph / Gap / Timeline / Leads -> Result Storage.
 * @project CASETHREAD
 */

const { test, describe, before, after } = require('node:test');
const assert = require('node:assert/strict');
const http = require('http');

process.env.NODE_ENV = 'test';
process.env.USE_MEMORY_STORE = 'true';

const jwt = require('jsonwebtoken');
const app = require('../server');
const { execute } = require('../database/connection');
const cEngineService = require('../services/cEngineService');
const { JWT_SECRET } = require('../middleware/auth');

let server;
let baseUrl;
let leadOfficerToken;
let unauthorizedOfficerToken;

before(async () => {
  // Start server on ephemeral port for end-to-end HTTP testing
  await new Promise((resolve) => {
    server = http.createServer(app);
    server.listen(0, '127.0.0.1', () => {
      const port = server.address().port;
      baseUrl = `http://127.0.0.1:${port}/api/v1`;
      resolve();
    });
  });

  // Issue tokens
  leadOfficerToken = jwt.sign(
    { officer_id: 1, badge_number: 'DET-8841', role: 'LEAD_OFFICER' },
    JWT_SECRET,
    { expiresIn: '1h' }
  );

  unauthorizedOfficerToken = jwt.sign(
    { officer_id: 99, badge_number: 'DET-9999', role: 'INVESTIGATOR' },
    JWT_SECRET,
    { expiresIn: '1h' }
  );
});

after(async () => {
  if (server) {
    await new Promise((resolve) => server.close(resolve));
  }
});

describe('CASETHREAD Phase 5 - End-to-End Integration & Case Simulation', () => {

  // 1. Authentication & Security
  test('1. Auth Enforcement & Invalid Credentials', async () => {
    const unauthRes = await fetch(`${baseUrl}/cases/1`);
    assert.strictEqual(unauthRes.status, 401, 'Should reject unauthenticated request with 401');

    const invalidTokenRes = await fetch(`${baseUrl}/cases/1`, {
      headers: { Authorization: 'Bearer INVALID_JWT_SIGNATURE' }
    });
    assert.strictEqual(invalidTokenRes.status, 403, 'Should reject invalid JWT with 403');
  });

  // 2. Case Dossier Retrieval
  test('2. Case Dossier Retrieval ("The Metro Vault Intrusion & Disappearance")', async () => {
    const res = await fetch(`${baseUrl}/cases/1`, {
      headers: { Authorization: `Bearer ${leadOfficerToken}` }
    });
    assert.strictEqual(res.status, 200);

    const body = await res.json();
    assert.strictEqual(body.success, true);
    assert.strictEqual(body.data.case_number, 'CASE-2026-0419');
    assert.strictEqual(body.data.title, 'The Metro Vault Intrusion & Disappearance');

    // Verify entity populations
    assert.ok(body.data.suspects.length >= 3, 'Must have at least 3 suspects');
    assert.ok(body.data.witnesses.length >= 2, 'Must have at least 2 witnesses');
    assert.ok(body.data.victims.length >= 1, 'Must have at least 1 victim');
    assert.ok(body.data.evidence.length >= 8, 'Must have multiple evidence records');
    assert.ok(body.data.timelines.length >= 8, 'Must have multiple timeline events');
  });

  // 3. Unauthorized Cross-Case Access Denial
  test('3. Unauthorized Case Access Denial (Officer Isolation)', async () => {
    // Detective 99 is an INVESTIGATOR who does not own Case 1
    const res = await fetch(`${baseUrl}/analysis/cases/1/run`, {
      method: 'POST',
      headers: { Authorization: `Bearer ${unauthorizedOfficerToken}` }
    });
    assert.strictEqual(res.status, 403, 'Unauthorized officer must receive 403 FORBIDDEN');
    const body = await res.json();
    assert.strictEqual(body.error.code, 'FORBIDDEN_UNAUTHORIZED_CASE_ACCESS');
  });

  // 4. Real Native C Engine Execution via IPC
  test('4. Real Native C Core Engine Execution via Node.js IPC', async () => {
    const res = await fetch(`${baseUrl}/analysis/cases/1/run`, {
      method: 'POST',
      headers: { Authorization: `Bearer ${leadOfficerToken}` }
    });
    assert.strictEqual(res.status, 200);

    const body = await res.json();
    assert.strictEqual(body.success, true);
    assert.strictEqual(body.data.case_id, 1);
    assert.ok(body.data.execution_latency_ms >= 0);

    const analysis = body.data.analysis;
    assert.strictEqual(analysis.status, 'SUCCESS');
    assert.match(analysis.engine_version, /^1\.0\.0/);

    // Verify metrics generated by C engine
    assert.ok(analysis.metrics.nodes_processed >= 6, 'Must process multiple nodes');
    assert.ok(analysis.metrics.edges_evaluated >= 4, 'Must evaluate multiple edges');
    assert.ok(analysis.metrics.gaps_detected >= 3, 'Must detect evidence gaps');
    assert.ok(analysis.metrics.anomalies_detected >= 1, 'Must detect spatiotemporal anomalies');
    assert.ok(analysis.metrics.leads_generated >= 2, 'Must generate prioritized leads');
  });

  // 5. Graph Topology & Connected Component Clustering (DFS)
  test('5. Graph Connected Components & Isolated Records in C', async () => {
    const res = await fetch(`${baseUrl}/cases/1/graph/components`, {
      headers: { Authorization: `Bearer ${leadOfficerToken}` }
    });
    assert.strictEqual(res.status, 200);

    const body = await res.json();
    assert.strictEqual(body.success, true);
    assert.ok(body.data.total_components >= 2, 'Must partition into at least 2 disconnected clusters');

    // Query isolated evidence
    const isoRes = await fetch(`${baseUrl}/cases/1/graph/isolated`, {
      headers: { Authorization: `Bearer ${leadOfficerToken}` }
    });
    assert.strictEqual(isoRes.status, 200);
    const isoBody = await isoRes.json();
    assert.strictEqual(isoBody.success, true);
    assert.ok(isoBody.data.isolated_nodes.length >= 1, 'Must identify isolated record (e.g. Abandoned Bicycle)');
  });

  // 6. BFS Shortest Path Traversal
  test('6. BFS Shortest Path Traversal Between Suspect and Vehicle', async () => {
    // Marcus Vance (Suspect 1) -> Damon Vance (Suspect 2) -> Vehicle 7XYZ99 (Evidence 3)
    const res = await fetch(`${baseUrl}/cases/1/graph/path?source_id=1&target_id=3&source_type=SUSPECT&target_type=EVIDENCE`, {
      headers: { Authorization: `Bearer ${leadOfficerToken}` }
    });
    assert.strictEqual(res.status, 200);

    const body = await res.json();
    assert.strictEqual(body.success, true);
    if (body.data.path_found) {
      assert.ok(body.data.path.length >= 2, 'Path must traverse intermediate associates');
    }
  });

  // 7. Evidence Gap Detection Verification
  test('7. Evidence Gap Detection Heuristics', async () => {
    const res = await fetch(`${baseUrl}/cases/1/graph`, {
      headers: { Authorization: `Bearer ${leadOfficerToken}` }
    });
    assert.strictEqual(res.status, 200);

    const body = await res.json();
    const gaps = body.data.evidence_gaps;
    assert.ok(Array.isArray(gaps) && gaps.length >= 3, 'Gaps array must have multiple detections');

    const categories = gaps.map(g => g.category);
    assert.ok(categories.includes('MISSING_TIMESTAMP'), 'Must flag missing timestamp gap');
    assert.ok(categories.includes('MISSING_SOURCE'), 'Must flag missing source provenance gap');
    assert.ok(categories.includes('UNVERIFIED_OBSERVATION'), 'Must flag uncorroborated tip gap');
  });

  // 8. Timeline Analysis & Spatiotemporal Anomaly Detection
  test('8. Spatiotemporal Anomaly Detection (Impossible Travel Velocity)', async () => {
    const res = await fetch(`${baseUrl}/cases/1/graph`, {
      headers: { Authorization: `Bearer ${leadOfficerToken}` }
    });
    assert.strictEqual(res.status, 200);

    const body = await res.json();
    const anomalies = body.data.timeline_anomalies;
    assert.ok(Array.isArray(anomalies) && anomalies.length >= 1, 'Must flag timeline contradictions');

    const speedAnomaly = anomalies.find(a => a.anomaly_type === 'IMPOSSIBLE_TRAVEL_SPEED');
    assert.ok(speedAnomaly, 'Must specifically flag IMPOSSIBLE_TRAVEL_SPEED anomaly');
    assert.ok(speedAnomaly.explanation.length > 10, 'Must have scientific explanation');
    assert.ok(speedAnomaly.suggested_check.length > 5, 'Must provide recommended check');
  });

  // 9. Prioritized Lead Generation & Database Persistence
  test('9. Investigative Lead Synthesis & Database Persistence', async () => {
    // 1. Run analysis to trigger C Engine synthesis and database persistence
    const runRes = await fetch(`${baseUrl}/analysis/cases/1/run`, {
      method: 'POST',
      headers: { Authorization: `Bearer ${leadOfficerToken}` }
    });
    assert.strictEqual(runRes.status, 200);

    // 2. Query persisted leads from MySQL / MemoryStore
    const leadsRes = await fetch(`${baseUrl}/leads/case/1`, {
      headers: { Authorization: `Bearer ${leadOfficerToken}` }
    });
    assert.strictEqual(leadsRes.status, 200);

    const leadsBody = await leadsRes.json();
    assert.ok(leadsBody.data.length >= 2, 'Case must have active investigative leads');

    const topLead = leadsBody.data[0];
    assert.ok(topLead.title, 'Lead must have a title');
    assert.ok(topLead.priority_score > 0, 'Lead must have positive composite score');
  });

  // 10. Edge Cases: Empty Case & Large Dataset
  test('10. Edge Cases: Empty Investigation & Large Dataset Scalability', async () => {
    // 10a: Test C Engine execution on completely empty case
    const emptyPayload = {
      case_id: 9999,
      entities: [],
      evidence: [],
      relationships: [],
      timeline: []
    };

    const emptyResult = await cEngineService.runAnalysis(emptyPayload);
    assert.strictEqual(emptyResult.status, 'SUCCESS');
    assert.strictEqual(emptyResult.metrics.nodes_processed, 0);
    assert.strictEqual(emptyResult.metrics.edges_evaluated, 0);

    // 10b: Test C Engine on large synthetic dataset (100 entities, 150 edges)
    const largeEntities = [];
    const largeEvidence = [];
    const largeRelationships = [];
    const largeTimeline = [];

    for (let i = 1; i <= 60; i++) {
      largeEntities.push({
        id: i,
        type: i % 2 === 0 ? 'SUSPECT' : 'WITNESS',
        label: `Person_${i}`,
        phone: `+1-555-${1000 + i}`
      });
    }

    for (let i = 1; i <= 40; i++) {
      largeEvidence.push({
        id: i,
        tracking_code: `EVD-LARGE-${i}`,
        category: 'CCTV',
        title: `Camera_${i}`,
        location: `Location_${i % 10}`,
        timestamp: 1700000000 + (i * 300),
        source: 'Municipal CCTV',
        verification_status: 'CONFIRMED_FACT',
        reliability_assessment: 'HIGH'
      });
    }

    for (let i = 1; i < 60; i++) {
      largeRelationships.push({
        id: i,
        source_type: 'SUSPECT',
        source_id: i,
        target_type: 'SUSPECT',
        target_id: i + 1,
        relation_type: 'ASSOCIATE',
        confidence_weight: 0.8
      });
    }

    const largePayload = {
      case_id: 8888,
      entities: largeEntities,
      evidence: largeEvidence,
      relationships: largeRelationships,
      timeline: largeTimeline
    };

    const largeStartTime = Date.now();
    const largeResult = await cEngineService.runAnalysis(largePayload);
    const largeDuration = Date.now() - largeStartTime;

    assert.strictEqual(largeResult.status, 'SUCCESS');
    assert.strictEqual(largeResult.metrics.nodes_processed, 100);
    assert.ok(largeDuration < 1000, `Execution on 100 nodes should be fast, took ${largeDuration}ms`);
  });

});
